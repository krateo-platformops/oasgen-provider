// The generator is the fifth input to a generated CRD and the only one no stored hash covered. oasHash
// covers the documents, resourceHash covers spec.resource, digest covers the rendered managed resources
// and authSecretDigest covers the referenced Secrets -- every one of them describes what goes IN, and an
// upgrade changes the function applied to it while leaving all four equal. Observe therefore reported
// "up to date" and a release's generation fixes never reached a CRD that already existed (#453).
//
// These arms assert on the Debug message rather than on the returned ExternalObservation, for the reason
// observe_resource_hash_test.go gives: several branches return the same {exists, upToDate} pair for
// different reasons, so that pair cannot say WHICH branch ran. The whole defect was a branch not running.

// externalWithGenerator reuses the fake-cluster fixture that gets Observe as far as the drift checks,
// then attaches the generator config under test.
func externalWithGenerator(t *testing.T, cr *definitionv1alpha1.RestDefinition, cfg GeneratorConfig, msgs, lines *[]string) *external {
	t.Helper()
	e := externalForHashTest(t, cr, msgs, lines)
	e.genCfg = cfg
	return e
}

const genDriftMsg = "Generator build changed"

// TestGeneratorChangedPredicate pins the predicate itself. Each false case is false for a DIFFERENT
// reason, and collapsing them would hide the two that matter: an opted-out operator must never be
// regenerated, and an unstamped binary must not report permanent drift.
func TestGeneratorChangedPredicate(t *testing.T) {
	for _, tc := range []struct {
		name   string
		cfg    GeneratorConfig
		stored string
		want   bool
		why    string
	}{
		{
			name:   "a different build regenerates once",
			cfg:    GeneratorConfig{Build: "0.53.0-abc1234", RegenerateOnUpgrade: true},
			stored: "0.52.0-def5678", want: true,
			why: "this is the whole point: the generator changed, so the schema may differ",
		},
		{
			name:   "the same build does not",
			cfg:    GeneratorConfig{Build: "0.53.0-abc1234", RegenerateOnUpgrade: true},
			stored: "0.53.0-abc1234", want: false,
			why: "steady state; otherwise every reconcile would re-render every CRD in the cluster",
		},
		{
			name:   "never stored regenerates once -- the activation path every existing cluster takes",
			cfg:    GeneratorConfig{Build: "0.53.0-abc1234", RegenerateOnUpgrade: true},
			stored: "", want: true,
			why: "the field is new, so every pre-existing RestDefinition has it empty; one re-render is correct because such a CRD may genuinely be stale",
		},
		{
			name:   "opted out, even against a different build",
			cfg:    GeneratorConfig{Build: "0.53.0-abc1234", RegenerateOnUpgrade: false},
			stored: "0.52.0-def5678", want: false,
			why: "OASGEN_PROVIDER_REGENERATE_ON_UPGRADE=false is the operator's staging escape hatch; if it does not actually suppress this, it is dead config",
		},
		{
			name:   "an unstamped binary is inert, not permanently drifting",
			cfg:    GeneratorConfig{Build: "", RegenerateOnUpgrade: true},
			stored: "0.52.0-def5678", want: false,
			why: "a plain `go build` stamps nothing; treating '' as a distinct build would re-render on every reconcile forever",
		},
		{
			name:   "unstamped and unstored agree trivially",
			cfg:    GeneratorConfig{Build: "", RegenerateOnUpgrade: true},
			stored: "", want: false,
			why: "nothing is known and nothing is claimed",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, tc.cfg.generatorChanged(tc.stored), tc.why)
		})
	}
}

// TestObserveReportsDriftWhenGeneratorBuildChanged is the regression test for #453. It asserts Observe
// REACHES the comparison -- a test on the predicate alone would reproduce the bug, which was that
// nothing consulted the generator at all. Same trap #224's test documents.
func TestObserveReportsDriftWhenGeneratorBuildChanged(t *testing.T) {
	cr := restDefinitionForHashTest()
	cr.Status.GeneratorBuild = "0.52.0-old0000" // generated by the previous release

	var msgs, lines []string
	e := externalWithGenerator(t, cr, GeneratorConfig{Build: "0.53.0-new1111", RegenerateOnUpgrade: true}, &msgs, &lines)

	obs, err := e.Observe(context.Background(), cr)
	require.NoError(t, err)
	t.Logf("observe trace:\n  %s", strings.Join(lines, "\n  "))
	assert.False(t, obs.ResourceUpToDate,
		"an upgraded generator must report drift, so the runtime calls Update and the CRD is re-rendered")
	assert.True(t, obs.ResourceExists, "the CRD is present; this is drift, not absence")
	assert.Contains(t, msgs, genDriftMsg,
		"the drift must come from the generator comparison specifically, not from an unrelated branch")
}

// TestObserveDoesNotReportGeneratorDriftWhenBuildUnchanged is the steady state. Without it a stable
// install would re-render every CRD and redeploy every controller on every reconcile.
func TestObserveDoesNotReportGeneratorDriftWhenBuildUnchanged(t *testing.T) {
	cr := restDefinitionForHashTest()
	cr.Status.GeneratorBuild = "0.53.0-new1111"

	var msgs, lines []string
	e := externalWithGenerator(t, cr, GeneratorConfig{Build: "0.53.0-new1111", RegenerateOnUpgrade: true}, &msgs, &lines)

	_, _ = e.Observe(context.Background(), cr)

	assert.NotContains(t, msgs, genDriftMsg, "the same generator must not be reported as drift")
}

// TestObserveHonoursTheRegenerateOptOut is the arm that proves the escape hatch is live rather than
// decorative. #454 found OASGEN_PROVIDER_DEBUG to be dead config -- the chart passes --debug explicitly,
// so the env var could never take effect and nothing ever noticed. A documented opt-out that does not
// suppress the behaviour it names is the same defect, and only an arm like this catches it.
func TestObserveHonoursTheRegenerateOptOut(t *testing.T) {
	cr := restDefinitionForHashTest()
	cr.Status.GeneratorBuild = "0.52.0-old0000" // a genuine mismatch, deliberately

	var msgs, lines []string
	e := externalWithGenerator(t, cr, GeneratorConfig{Build: "0.53.0-new1111", RegenerateOnUpgrade: false}, &msgs, &lines)

	_, _ = e.Observe(context.Background(), cr)

	assert.NotContains(t, msgs, genDriftMsg,
		"with the opt-out set, a generator mismatch must not provoke a re-render; the operator has accepted that fixes do not apply")
}

// TestObserveDoesNotReportGeneratorDriftFromAnUnstampedBinary covers the local-development path. A plain
// `go build` leaves main.Build empty; if that counted as a distinct generator, every developer's cluster
// would re-render on every single reconcile.
func TestObserveDoesNotReportGeneratorDriftFromAnUnstampedBinary(t *testing.T) {
	cr := restDefinitionForHashTest()
	cr.Status.GeneratorBuild = "0.52.0-old0000"

	var msgs, lines []string
	e := externalWithGenerator(t, cr, GeneratorConfig{Build: "", RegenerateOnUpgrade: true}, &msgs, &lines)

	_, _ = e.Observe(context.Background(), cr)

	assert.NotContains(t, msgs, genDriftMsg,
		"an unstamped binary has no identity to compare, so it must claim nothing")
}

// TestObserveReportsDriftWhenGeneratorBuildNeverStored is the path EVERY existing cluster takes when this
// ships: the status field is new, so it is empty everywhere. One bounded re-render per RestDefinition,
// which is the mechanism that carries a release's generation fixes to kinds that already exist.
func TestObserveReportsDriftWhenGeneratorBuildNeverStored(t *testing.T) {
	cr := restDefinitionForHashTest()
	cr.Status.GeneratorBuild = "" // as every RestDefinition created before this field existed

	var msgs, lines []string
	e := externalWithGenerator(t, cr, GeneratorConfig{Build: "0.53.0-new1111", RegenerateOnUpgrade: true}, &msgs, &lines)

	obs, err := e.Observe(context.Background(), cr)
	require.NoError(t, err)
	assert.False(t, obs.ResourceUpToDate, "an unstored generator must re-render once rather than stay silently stale")
	assert.Contains(t, msgs, genDriftMsg)
}
