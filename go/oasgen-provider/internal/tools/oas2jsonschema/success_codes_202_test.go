package oas2jsonschema

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// A create that answers 202 had no findable response schema, and no way for an author to say otherwise.
//
// The generator's default is {200, 201} and nothing could widen it, so an ASYNCHRONOUS CREATE -- an
// ordinary shape, and the one this repo's async.poll support exists for -- rendered
// "no suitable response schema found for action 'create'". A per-verb successCodes field already existed
// and its own documentation named 202, but it was wired to rest-dynamic-controller's runtime and never
// reached the generator (#804).
//
// MEASURED BY openstack-nova-operator-kog WITH FIVE CONTROLS on oasgen-provider 0.80.0, across six Nova
// documents: creates at '200' x4 and '201' x1 warned about nothing, the single create at '202' warned.
// Deletes declared at '202' produced nothing, so it was specific to the create action rather than to 202.
// Their document was correct -- Nova's POST /servers genuinely returns 202 Accepted -- so the fix had to
// be here rather than in the OAS.
func TestAVerbsSuccessCodesWidenTheGeneratorsSet(t *testing.T) {
	created := &Schema{Type: []string{"object"}, Properties: []Property{
		{Name: "id", Schema: &Schema{Type: []string{"string"}}},
	}}

	// A create that answers ONLY 202, which is what Nova's POST /servers does.
	doc := &mockOASDocument{
		Paths: map[string]*mockPathItem{
			"/servers": {
				Ops: map[string]Operation{
					"post": &mockOperation{
						Responses: map[int]ResponseInfo{
							202: {Content: map[string]*Schema{"application/json": created}},
						},
					},
				},
			},
			"/ordinary": {
				Ops: map[string]Operation{
					"post": &mockOperation{
						Responses: map[int]ResponseInfo{
							201: {Content: map[string]*Schema{"application/json": created}},
						},
					},
				},
			},
		},
	}
	cfg := DefaultGeneratorConfig()
	require.Equal(t, []int{200, 201}, cfg.SuccessCodes,
		"the premise: if the default ever gains 202, every case below proves something else")

	t.Run("202 WITHOUT the declaration is still not found", func(t *testing.T) {
		_, err := ExtractSchemaForAction(NewDocumentSet(doc),
			[]Verb{{Action: ActionCreate, Path: "/servers", Method: "post"}}, ActionCreate, cfg)
		require.Error(t, err, "this is the defect as reported, and it must still reproduce or the case "+
			"below proves nothing")
		assert.Contains(t, err.Error(), "no suitable response schema found")
	})

	t.Run("202 WITH the declaration is found", func(t *testing.T) {
		schema, err := ExtractSchemaForAction(NewDocumentSet(doc),
			[]Verb{{Action: ActionCreate, Path: "/servers", Method: "post", SuccessCodes: []int{202}}},
			ActionCreate, cfg)
		require.NoError(t, err, "an author declaring successCodes: [202] must be able to tell the "+
			"generator what their async create answers")
		assert.Equal(t, created, schema)
	})

	t.Run("declaring 202 does not LOSE 201", func(t *testing.T) {
		schema, err := ExtractSchemaForAction(NewDocumentSet(doc),
			[]Verb{{Action: ActionCreate, Path: "/ordinary", Method: "post", SuccessCodes: []int{202}}},
			ActionCreate, cfg)
		require.NoError(t, err, "the field is documented as ADDITIONAL, never replacing")
		assert.Equal(t, created, schema)
	})

	t.Run("the merge does not mutate the shared config", func(t *testing.T) {
		assert.Equal(t, []int{200, 201}, cfg.SuccessCodes,
			"appending onto config.SuccessCodes would leak one verb's codes into every later verb AND "+
				"into the next resource generated by the same config")
	})
}

// The conversion from the CR is where a field like this goes missing: helper.go's own comment says it is
// "the only place a ResourceConfig is built from a CR, so a field the generator reads and this function
// does not set is silently zero". SuccessCodes was exactly that field.
func TestTheGeneratorsVerbHasSomewhereToPutIt(t *testing.T) {
	v := Verb{Action: "create", SuccessCodes: []int{202}}
	require.Equal(t, []int{202}, v.SuccessCodes,
		"without this field on the generator's Verb there is nothing for toDomainVerbs to copy into, "+
			"which is why the runtime had the value and the generator did not")
}
